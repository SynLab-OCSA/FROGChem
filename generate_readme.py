"""Genera README.md e docs/cli/*.md dalle definizioni dei comandi CLI.

Unica fonte di verità: le classi CLICommand (description, outputs, examples, argparse).
Uso: python generate_readme.py [--docs-only]

Pagine per comando: docs/cli/<comando>.md (vedi command_page); testo scritto a mano in
docs/cli/_parts/<comando>/how_it_works.md, esempi reali in docs/cli/_examples/ (docs/build_examples.py).
"""
import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS_CLI = ROOT / "docs" / "cli"
GENERATED_NOTE = ("<!-- Generated by generate_readme.py from the CLI definitions in src/frogchem/cli. "
                  "Do not edit by hand. -->")
KIND_LABEL = {"table": "Terminal", "file": "File", "plot": "Plot"}


def load_commands():
    from frogchem.cli.base import load_all_commands
    return dict(sorted(load_all_commands().items()))


def help_texts(cls):
    """--help of the command, plus the help of each subcommand."""
    parser = cls().build_parser()
    texts = [parser.format_help()]
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for sub in action.choices.values():
                texts.append(sub.format_help())
    return texts


def md_cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def outputs_table(cls):
    rows = ["| Kind | Name | When | Description |", "|---|---|---|---|"]
    for o in cls.outputs:
        when = f"`{o.when}`" if o.when else "always"
        rows.append(f"| {KIND_LABEL[o.kind]} | `{md_cell(o.name)}` | {when} | {md_cell(o.description)} |")
    return "\n".join(rows)


def examples_block(cls):
    out = []
    for cmd, desc in cls.examples:
        if desc:
            out.append(f"# {desc}")
        out.append(cmd)
    return "```bash\n" + "\n".join(out) + "\n```"


def guide_sections(cls, level="##"):
    """'What it is for / What you need / How to use it / What to expect' from cls.guide."""
    g = getattr(cls, "guide", None)
    if g is None:
        return []
    import inspect as _inspect
    clean = lambda s: _inspect.cleandoc(s).strip()
    parts = [f"{level}# What it is for", "", clean(g.why), ""]
    parts += [f"{level}# What you need", "", clean(g.needs), ""]
    parts += [f"{level}# How to use it", ""]
    parts += [f"{i}. {clean(step)}" for i, step in enumerate(g.how, 1)]
    parts += ["", f"{level}# What to expect", "", clean(g.expect), ""]
    return parts


def command_section(cls, level="##"):
    parts = [f"{level} `{cls.name}`", "", cls.summary(), ""]
    parts += guide_sections(cls, level)
    parts += [f"{level}# Outputs", "", outputs_table(cls), ""]
    parts += [f"{level}# Examples", "", examples_block(cls), ""]
    parts += [f"{level}# Usage", ""]
    for text in help_texts(cls):
        parts += ["```text", text.rstrip(), "```", ""]
    return "\n".join(parts)


README_INTRO = """\
**FROG** is a quality-of-life toolbox for computational chemists. It turns the output of
quantum-chemistry programs (**ORCA** 4–6, **Gaussian** 09/16) into the numbers and pictures you need
for a paper or a thesis, with one command per task. The name says what it does:

| | | |
|---|---|---|
| **F** | **Find** | read energies, geometries, frequencies, orbitals, charges, NMR and TD-DFT data from the output files |
| **R** | **Refine** | recompute and improve them: quasi-RRHO free energies, Boltzmann averages, simulated spectra, %V_bur |
| **O** | **Organize** | sort, split, compare and align structures and conformer ensembles |
| **G** | **Graph** | draw the results: UV/ECD and NMR spectra, steric maps, reaction profiles, CIE diagrams |

In Python the package is imported as `frogchem`; the command-line tools are called `frog-<tool>`
(e.g. `frog-rrho`, `frog-nmr`, `frog-tddft`), and `frog` alone lists them all.
"""


CONVENTIONS_SUMMARY = """\
All commands share the same output rules (full text: [docs/cli/conventions.md](docs/cli/conventions.md)):

* **stdout = data, stderr = messages.** Tables go to stdout; banner, progress, `✔ Saved …` notices,
  warnings and errors go to stderr. `-q` silences messages, `-v` enables debug logging.
* **Tables:** `--format table|json|csv` prints one document for the whole run;
  `--table-file PATH` writes all tables to a `.json`, `.csv` or `.txt` file.
* **Files:** per-input files are written next to the input as `<stem>_<tag>.<ext>` (`--out-dir` redirects
  them); `-o/--output` is always the primary output path; inputs are never overwritten.
* **Plots:** saved, never shown by default (`--show` opens them); `--fig-format png|svg|pdf`, `--dpi` (300);
  one shared matplotlib style.
* **Flags:** kebab-case long flags; reserved short flags `-o` output, `-i` 0-based atom indices,
  `-t` threshold, `-w` write, `-f` force, `-T` temperature, `-c` checkpoint.
* **Numbering:** atoms are 0-based; TD-DFT states are S1, S2, …, T1, …, D1, … (numbered within each multiplicity,
  S0 = ground state) in every table and in `--dct-states` / `--soc-states`.
* Every `--help` ends with an **outputs** section (tables, files, plots and the flags that produce them)
  and **examples**.
"""


