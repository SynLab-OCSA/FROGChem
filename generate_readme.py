# Commands left out of the documentation (the code is untouched).
EXCLUDED_FROM_DOCS = {
    "frog-autoprofile",   # reaction profiles from outputs: covered by the Streamlit app
    "frog-md",            # no example data yet
    "frog-plot-neb",      # no example data yet
}

BADGE = {  # short category label + sphinx-design badge colour
    "parsing": ("Parsing", "primary"),
    "thermo": ("Thermochemistry", "danger"),
    "geometry": ("Geometry", "success"),
    "nmr": ("NMR", "info"),
    "spectroscopy": ("Spectroscopy & grids", "warning"),
    "substituter": ("Substitution", "secondary"),
}
LEGACY_PAGES = ["parsing", "thermo", "geometry", "nmr", "spectroscopy", "substituter"]


def documented(commands):
    return {n: c for n, c in commands.items() if n not in EXCLUDED_FROM_DOCS}


def badge(cls):
    label, colour = BADGE.get(cls.category, (cls.category, "secondary"))
    return f"{{bdg-{colour}}}`{label}`"


def _clean(text):
    import inspect as _inspect
    return _inspect.cleandoc(text).strip()


def _format_action(action):
    """(argument, default, description) for one argparse action."""
    if action.option_strings:
        flags = ", ".join(f"`{s}`" for s in action.option_strings)
        if action.nargs != 0:
            if action.choices:
                meta = "{" + ",".join(map(str, action.choices)) + "}"
            else:
                meta = action.metavar or action.dest.upper()
                if isinstance(meta, tuple):
                    meta = " ".join(meta)
            if action.nargs in ("+", "*"):
                meta += " …"
            elif action.nargs == "?":
                meta = f"[{meta}]"
            flags += f" `{meta}`"
    else:
        meta = action.metavar or action.dest
        flags = f"`{meta}`" + (" …" if action.nargs in ("+", "*") else "")
    default = action.default
    if action.nargs == 0 or default in (None, argparse.SUPPRESS, [], ""):
        default = "required" if getattr(action, "required", False) else ""
    else:
        default = f"`{default}`"
    if not action.option_strings and action.nargs not in ("?", "*"):
        default = "required"
    return flags, default, md_cell(action.help or "")


def arguments_table(cls):
    """Markdown tables of the arguments, one per argparse group (shared -v/-q/--format left out)."""
    shared = {"help", "verbose", "quiet", "format", "table_file"}
    parser = cls().build_parser()
    blocks = []
    for group in parser._action_groups:
        actions = [a for a in group._group_actions
                   if a.dest not in shared and not isinstance(a, argparse._SubParsersAction)]
        if not actions:
            continue
        title = {"positional arguments": "Positional arguments", "options": "Options",
                 "optional arguments": "Options"}.get(group.title, group.title.capitalize())
        rows = [f"**{title}**", "", "| Argument | Default | Description |", "|---|---|---|"]
        rows += ["| {} | {} | {} |".format(*_format_action(a)) for a in actions]
        blocks.append("\n".join(rows))
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            subs = ", ".join(f"`{n}`" for n in action.choices)
            blocks.insert(0, f"This command has sub-commands: {subs}. "
                             "Their options are listed in the full reference below.")
    blocks.append("Shared by every command: `-v/--verbose`, `-q/--quiet`"
                  + (", `--format {table,json,csv}`, `--table-file PATH`" if cls.has_tables else "")
                  + " — see [CLI conventions](conventions.md).")
    return "\n\n".join(blocks)


def _fragment(rel, missing_note):
    """MyST include of a hand-written fragment, or a visible note when it does not exist yet."""
    if (DOCS_CLI / rel).exists():
        return f"```{{include}} {rel}\n```"
    return f":::{{note}}\n{missing_note}\n:::"


def command_page(cls):
    g = cls.guide
    name = cls.name
    parts = [f"({name})=", f"# {name}", "", GENERATED_NOTE, "",
             f"{badge(cls)} {cls.summary()}", ""]

    parts += ["## What it does", ""]
    parts += [_clean(g.why) if g else cls.summary(), ""]

    parts += ["## How it works", "",
              _fragment(f"_parts/{name}/how_it_works.md",
                        f"Not written yet: add `docs/cli/_parts/{name}/how_it_works.md`."), ""]

    parts += ["## Input", ""]
    if g:
        parts += [_clean(g.needs), ""]
    parts += ["### Arguments", "", arguments_table(cls), ""]

    parts += ["## Output", "", outputs_table(cls), ""]
    if g:
        parts += ["### How to read it", "", _clean(g.expect), ""]

    if g:
        parts += ["## Step by step", ""]
        parts += [f"{i}. {_clean(step)}" for i, step in enumerate(g.how, 1)]
        parts += [""]

    parts += ["## Real example", "",
              _fragment(f"_examples/{name}.md",
                        f"No example yet: write `docs/cli/_examples/{name}.yaml` and run "
                        "`python docs/build_examples.py " + name + "`."), ""]

    parts += ["## Full reference", "",
              f"Every option, as printed by `{name} --help`:", ""]
    for i, text in enumerate(help_texts(cls)):
        title = f"`{name} --help`" if i == 0 else "sub-command `--help`"
        parts += [f":::{{dropdown}} {title}", "```text", text.rstrip(), "```", ":::", ""]
    return "\n".join(parts)


def overview_page(commands):
    """docs/cli/reference.md: every command on one screen as a grid of cards."""
    cards = []
    for name, cls in commands.items():
        cards += [f":::{{grid-item-card}} {name}", f":link: {name}", ":link-type: ref", "",
                  cls.summary(), "+++", badge(cls), ":::", ""]
    by_cat = []
    for cat, (title, _intro) in _categories().items():
        members = [n for n, c in commands.items() if c.category == cat]
        if members:
            by_cat.append(f"| {BADGE.get(cat, (title,))[0]} | " + ", ".join(f"[`{m}`]({m}.md)" for m in members) + " |")
    return f"""# All commands at a glance

{GENERATED_NOTE}

FROG provides **{len(commands)} documented command-line tools**. Each one can be run directly or through
the launcher:

```bash
frog-rrho files/opt.out
frog rrho files/opt.out
frog            # list all tools
```

Every page has the same sections: **What it does**, **How it works**, **Input**, **Output**,
**Real example** (run on the files shipped in the `files/` folder of the repository) and **Full reference**.

::::{{grid}} 1 2 3 3
:gutter: 2

{chr(10).join(cards)}
::::

## By topic

| Topic | Commands |
|---|---|
{chr(10).join(by_cat)}

## Shared options"""


def _categories():
    from frogchem.cli.base import CATEGORIES
    return CATEGORIES


def legacy_stub(category, commands):
    title = _categories()[category][0]
    links = "\n".join(f"* [`{n}`]({n}.md)" for n, c in commands.items() if c.category == category)
    return f"""---
orphan: true
---

# {title} CLI Tools

{GENERATED_NOTE}

This page has moved: every command now has its own page.

{links}

See [All commands at a glance](reference.md).
"""


def write_docs(commands):
    commands = documented(commands)
    for name, cls in commands.items():
        (DOCS_CLI / f"{name}.md").write_text(command_page(cls), encoding="utf-8")
    for category in LEGACY_PAGES:
        (DOCS_CLI / f"{category}_tools.md").write_text(legacy_stub(category, commands), encoding="utf-8")
    (DOCS_CLI / "reference.md").write_text(overview_page(commands) + SHARED_OPTIONS, encoding="utf-8")
    return commands


SHARED_OPTIONS = """

| Flag | Available on | Purpose |
|---|---|---|
| `-v`, `--verbose` | all | Debug logging |
| `-q`, `--quiet` | all | Hide banner, info and saved-file messages |
| `--format {table,json,csv}` | commands with tables | Format of the tables on stdout |
| `--table-file PATH` | commands with tables | Write all tables to `.json` / `.csv` / `.txt` |
| `-o`, `--output PATH` | commands with a primary output | Primary output file (or prefix) |
| `--out-dir DIR` | commands with per-input files | Where per-input files go (default: next to the input) |
| `--plot [PATH]` | commands with optional plots | Save the plot |
| `--fig-format`, `--dpi`, `--show` | commands with plots | Image format, resolution, interactive window |
| `-c`, `--checkpoint`, `--read-boltzmann`, `-e`, `-T`, `--individual` | ensemble commands | Boltzmann averaging |

See [CLI Output Conventions](conventions.md) for the complete rules.
"""


def main():
    ap = argparse.ArgumentParser(description="Generate README.md and docs/cli/*.md from the CLI definitions.")
    ap.add_argument("--docs-only", action="store_true", help="Only write docs/cli, leave README.md untouched")
    opts = ap.parse_args()
    os.environ.setdefault("COLUMNS", "100")
    commands = load_commands()
    if not opts.docs_only:
        write_readme(commands)
    documented_cmds = write_docs(commands)
    print(f"✅ docs/cli: {len(documented_cmds)} command pages "
          f"({len(commands) - len(documented_cmds)} excluded)"
          + ("" if opts.docs_only else "; README.md updated") + ".")


if __name__ == "__main__":
    # Aggiungi la cartella src al path se non installato
    sys.path.insert(0, str(ROOT / "src"))
    main()
