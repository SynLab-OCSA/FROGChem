#!/usr/bin/env python3
"""Run the real examples of the CLI pages and write ``docs/cli/_examples/<command>.md``.

Each command page (generated by ``generate_readme.py``) includes ``docs/cli/_examples/<command>.md`` in its
*Real example* section. That file is produced here from a small spec, ``docs/cli/_examples/<command>.yaml``,
by running the commands on a scratch copy of the repository data, so the output shown in the docs is the
real output of the current code.

Usage::

    python docs/build_examples.py                 # every spec
    python docs/build_examples.py frog-rrho     # one or more commands
    python docs/build_examples.py --keep          # keep the scratch folder (path is printed)

Spec format (YAML)::

    intro: |                       # optional, Markdown shown before the steps
      What the example shows.
    data:                          # optional, input files listed under "Files used"
      - path: files/opt.out
        about: ORCA r2SCAN-3c Opt+Freq of a Ru complex
    steps:
      - text: |                    # optional, Markdown before the command
          Compute G at 298.15 K.
        cmd: frog-rrho files/opt.out    # run from the scratch root (contains files/ and tests/)
        columns: 180               # optional, terminal width for the tables (default 180)
        output: full               # full (default) | none | head:N | tail:N
        hidden: false              # true = run it (e.g. to prepare an input) but do not show it
        expect_rc: 0               # optional, expected exit code (default 0)
        show_files:                # optional, text files produced by the command
          - path: files/opt.xyz
            lines: 15              # optional, first N lines (default 25)
            lang: text
        images:                    # optional, figures produced by the command
          - path: files/opt_steric_map.svg
            caption: Steric map seen from +Z.
            width: 70%
        after: |                   # optional, Markdown after the output (how to read it)
          ...
    outro: |                       # optional, Markdown at the end

Images are copied to ``docs/_static/cli/<command>/``. A spec that fails (unexpected exit code,
missing image) leaves the previous ``.md`` untouched and is reported at the end.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

DOCS = Path(__file__).resolve().parent
ROOT = DOCS.parent
EXAMPLES = DOCS / "cli" / "_examples"
STATIC = DOCS / "_static" / "cli"
DATA_DIRS = ["files", "tests/data"]          # copied into the scratch root, same relative paths
NOTE = "<!-- Generated by docs/build_examples.py from {name}.yaml. Edit the .yaml, not this file. -->"

ANSI = re.compile(r"\x1b\[[0-9;?]*[A-Za-z]")


def make_scratch() -> Path:
    """Scratch root with a real copy of the example data and frog-* launchers.

    The data are copied, not hard-linked: some commands rewrite existing output names in place
    (e.g. files/opt_final.xyz), and through a hard link that would modify the repository copy.
    """
    scratch = Path(tempfile.mkdtemp(prefix="frog_examples_"))
    for rel in DATA_DIRS:
        src = ROOT / rel
        if src.exists():
            shutil.copytree(src, scratch / rel, copy_function=shutil.copy2,
                            ignore=shutil.ignore_patterns(".DS_Store", "__pycache__", ".ruff_cache"))
    bindir = scratch / ".bin"
    bindir.mkdir()
    sys.path.insert(0, str(ROOT / "src"))
    from frogchem.cli.base import load_all_commands
    names = list(load_all_commands())
    for name in names + ["frog"]:
        sub = "" if name == "frog" else " " + name.removeprefix("frog-")
        launcher = bindir / name
        launcher.write_text(f'#!/bin/sh\nexec "{sys.executable}" -m frogchem{sub} "$@"\n')
        launcher.chmod(0o755)
    return scratch


def clean_output(text: str, scratch: Path) -> str:
    text = ANSI.sub("", text).replace(str(scratch) + "/", "").replace(str(scratch), ".")
    lines = text.splitlines()
    out, in_banner = [], False
    for i, line in enumerate(lines):
        # the banner is a 3-line box whose middle line is the command name in capitals
        if line.startswith("╭") and i + 2 < len(lines) and lines[i + 2].startswith("╰") \
                and re.fullmatch(r"│\s*FROG[\w\- ]*\s*│", lines[i + 1].strip()):
            in_banner = True
            skip = 3
        if in_banner:
            skip -= 1
            if skip == 0:
                in_banner = False
            continue
        out.append(line.rstrip())
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def plain_alt(text: str) -> str:
    """Alt text safe for directive options (parsed as YAML by older myst-parser): no Markdown, no ': '."""
    text = re.sub(r"[`*_]", "", " ".join(text.split()))
    text = text.replace(": ", " - ").replace(" #", " ")
    return text.lstrip("-?[]{}!&*|>'\"%@ ") or "figure"


def trim(text: str, mode: str) -> str:
    if mode in (None, "full"):
        return text
    kind, _, n = mode.partition(":")
    lines = text.splitlines()
    n = int(n or 20)
    if kind == "head" and len(lines) > n:
        return "\n".join(lines[:n] + ["…"])
    if kind == "tail" and len(lines) > n:
        return "\n".join(["…"] + lines[-n:])
    return text


def run_step(step, scratch: Path) -> str:
    env = dict(os.environ)
    env.update({
        "PATH": f"{scratch / '.bin'}{os.pathsep}{env.get('PATH', '')}",
        "PYTHONPATH": f"{ROOT / 'src'}{os.pathsep}{env.get('PYTHONPATH', '')}",
        "COLUMNS": str(step.get("columns", 180)),
        "MPLBACKEND": "Agg",
        "NO_COLOR": "1",
        "TERM": "dumb",
        "PYTHONWARNINGS": "ignore",
    })
    proc = subprocess.run(step["cmd"], shell=True, cwd=scratch, env=env, text=True,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          timeout=step.get("timeout", 900))
    rc_expected = step.get("expect_rc", 0)
    if proc.returncode != rc_expected:
        raise RuntimeError(f"`{step['cmd']}` exited with {proc.returncode} (expected {rc_expected}):\n"
                           + proc.stdout[-3000:])
    return clean_output(proc.stdout, scratch)


def build(name: str, scratch: Path) -> str:
    spec = yaml.safe_load((EXAMPLES / f"{name}.yaml").read_text(encoding="utf-8")) or {}
    md = [NOTE.format(name=name), ""]
    if spec.get("intro"):
        md += [spec["intro"].strip(), ""]
    if spec.get("data"):
        md += ["**Files used** (from the repository):", ""]
        md += [f"* `{d['path']}`" + (f" — {d['about']}" if d.get("about") else "") for d in spec["data"]]
        md += [""]
    img_dir = STATIC / name
    copied = []
    for step in spec.get("steps", []):
        out = run_step(step, scratch)
        if step.get("hidden"):
            continue
        if step.get("text"):
            md += [step["text"].strip(), ""]
        md += ["```bash", step["cmd"].strip(), "```", ""]
        mode = step.get("output", "full")
        if mode != "none" and out:
            md += ["```text", trim(out, mode), "```", ""]
        for f in step.get("show_files", []):
            path = scratch / f["path"]
            if not path.exists():
                raise RuntimeError(f"{name}: expected file {f['path']} was not produced")
            lines = path.read_text(errors="replace").splitlines()
            n = f.get("lines", 25)
            body = lines[:n] + (["…"] if len(lines) > n else [])
            text = "\n".join(body)
            fence = "`" * max(3, max((len(m) for m in re.findall(r"`{3,}", text)), default=0) + 1)
            md += [f"`{f['path']}`" + (f" (first {n} lines)" if len(lines) > n else "") + ":", "",
                   f"{fence}{f.get('lang', 'text')}", text, fence, ""]
        for im in step.get("images", []):
            src = scratch / im["path"]
            if not src.exists():
                raise RuntimeError(f"{name}: expected image {im['path']} was not produced")
            if not copied:
                img_dir.mkdir(parents=True, exist_ok=True)
            dst = img_dir / src.name
            shutil.copy2(src, dst)
            copied.append(dst)
            caption = (im.get("caption") or "").strip()
            md += [f"```{{figure}} /_static/cli/{name}/{src.name}", f":width: {im.get('width', '80%')}",
                   f":alt: {plain_alt(caption or src.name)}", "", caption, "```", ""]
        if step.get("after"):
            md += [step["after"].strip(), ""]
    if spec.get("outro"):
        md += [spec["outro"].strip(), ""]
    (EXAMPLES / f"{name}.md").write_text("\n".join(md).rstrip() + "\n", encoding="utf-8")
    return f"{name}: ok ({len(copied)} image(s))"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("commands", nargs="*", help="Commands to build (default: every .yaml spec)")
    ap.add_argument("--keep", action="store_true", help="Keep the scratch folder")
    opts = ap.parse_args()
    names = opts.commands or sorted(p.stem for p in EXAMPLES.glob("*.yaml"))
    missing = [n for n in names if not (EXAMPLES / f"{n}.yaml").exists()]
    if missing:
        sys.exit(f"No spec for: {', '.join(missing)} (expected docs/cli/_examples/<command>.yaml)")
    scratch = make_scratch()
    failed = []
    try:
        for name in names:
            try:
                print(build(name, scratch))
            except Exception as e:          # report and continue with the next spec
                failed.append(name)
                print(f"{name}: FAILED\n{e}", file=sys.stderr)
    finally:
        if opts.keep:
            print(f"scratch folder kept: {scratch}")
        else:
            shutil.rmtree(scratch, ignore_errors=True)
    if failed:
        sys.exit(f"{len(failed)} example(s) failed: {', '.join(failed)}")


if __name__ == "__main__":
    main()
