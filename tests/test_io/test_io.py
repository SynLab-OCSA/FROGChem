class TestReadXYZMixedFrames:
    def test_frames_with_different_atom_counts(self, tmp_path):
        f = tmp_path / "mixed.xyz"
        f.write_text(
            "3\nwater\nO 0.0 0.0 0.0\nH 0.0 0.0 0.96\nH 0.93 0.0 -0.24\n"
            "2\nH2\nH 0.0 0.0 0.0\nH 0.74 0.0 0.0\n"
            "1\nHe\nHe 1.0 2.0 3.0\n"
        )
        atoms, coords, comments = read_xyz(str(f))
        assert atoms == [["O", "H", "H"], ["H", "H"], ["He"]]
        assert comments == ["water", "H2", "He"]
        assert [c.shape for c in coords] == [(3, 3), (2, 3), (1, 3)]
        np.testing.assert_allclose(coords[2][0], [1.0, 2.0, 3.0])

    def test_trailing_blank_lines(self, tmp_path):
        f = tmp_path / "blank.xyz"
        f.write_text("2\nH2\nH 0.0 0.0 0.0\nH 0.74 0.0 0.0\n\n\n")
        atoms, coords, comments = read_xyz(str(f))
        assert atoms == [["H", "H"]]

    def test_truncated_last_frame_is_dropped(self, tmp_path):
        # e.g. a trajectory still being written: keep complete frames, warn about the rest
        f = tmp_path / "partial.xyz"
        f.write_text("2\nH2\nH 0.0 0.0 0.0\nH 0.74 0.0 0.0\n3\nwater\nO 0.0 0.0 0.0\n")
        with pytest.warns(UserWarning):
            atoms, coords, comments = read_xyz(str(f))
        assert atoms == [["H", "H"]]

    def test_bad_atom_count_line_raises(self, tmp_path):
        f = tmp_path / "bad.xyz"
        f.write_text("2\nH2\nH 0.0 0.0 0.0\nH 0.74 0.0 0.0\nfoo\nbar\n")
        with pytest.raises(ValueError):
            read_xyz(str(f))


class TestXyzToRdkitMol:
    WATER = "3\nwater\nO 0.0 0.0 0.0\nH 0.0 0.0 0.96\nH 0.93 0.0 -0.24\n"

    def test_multi_xyz_uses_first_frame(self, tmp_path):
        pytest.importorskip("rdkit")
        from frogchem.io import xyz_to_rdkit_mol
        f = tmp_path / "multi.xyz"
        f.write_text(self.WATER + self.WATER.replace("water", "water 2"))
        mol = xyz_to_rdkit_mol(str(f))
        assert mol.GetNumAtoms() == 3
        assert [a.GetSymbol() for a in mol.GetAtoms()] == ["O", "H", "H"]

    def test_frame_selection_and_positions(self, tmp_path):
        pytest.importorskip("rdkit")
        from frogchem.io import xyz_to_rdkit_mol
        f = tmp_path / "multi.xyz"
        f.write_text(self.WATER + "2\nH2\nH 0.0 0.0 0.0\nH 0.74 0.0 0.0\n")
        mol = xyz_to_rdkit_mol(str(f), frame=1)
        assert mol.GetNumAtoms() == 2
        pos = mol.GetConformer().GetAtomPosition(1)
        assert (pos.x, pos.y, pos.z) == pytest.approx((0.74, 0.0, 0.0))
